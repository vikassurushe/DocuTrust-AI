from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak

def build_pdf_report(case):
    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4, rightMargin=18*mm, leftMargin=18*mm,
        topMargin=16*mm, bottomMargin=16*mm
    )
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="Small", parent=styles["BodyText"], fontSize=8, leading=10))
    story = [
        Paragraph("DocuTrust AI — Investigation Dossier", styles["Title"]),
        Paragraph(f"<b>Case:</b> {case.get('case_name','')}", styles["BodyText"]),
        Paragraph(f"<b>Reviewer:</b> {case.get('reviewer','')}", styles["BodyText"]),
        Paragraph(f"<b>Generated:</b> {case.get('generated_at','')}", styles["Small"]),
        Spacer(1, 8),
        Paragraph("1. Executive Summary", styles["Heading2"]),
        Paragraph(
            f"This prototype processed {len(case.get('documents', []))} document(s) and identified "
            f"{len(case.get('findings', []))} potential cross-document discrepancy/discrepancies. "
            "These are review signals and must not be interpreted as confirmed fraud.",
            styles["BodyText"]
        ),
        Spacer(1, 8),
        Paragraph("2. Document Overview", styles["Heading2"]),
    ]
    rows = [["Document", "Pages", "SHA-256"]]
    for d in case.get("documents", []):
        rows.append([
            d.get("filename", ""),
            str(len(d.get("pages", []))),
            d.get("sha256", "")[:18] + "..."
        ])
    t = Table(rows, colWidths=[75*mm, 20*mm, 65*mm], repeatRows=1)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#0D2343")),
        ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("GRID", (0,0), (-1,-1), 0.4, colors.HexColor("#B8C4D3")),
        ("FONTSIZE", (0,0), (-1,-1), 8),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, colors.HexColor("#F0F5FB")]),
    ]))
    story += [t, Spacer(1, 8), Paragraph("3. Cross-Document Findings", styles["Heading2"])]
    if case.get("findings"):
        for f in case["findings"]:
            story.append(Paragraph(
                f"<b>{f.get('Finding ID')}</b> — {f.get('Category')}<br/>"
                f"<b>Field:</b> {f.get('Field')}<br/>"
                f"<b>Observed values:</b> {f.get('Observed values')}<br/>"
                f"<b>Evidence sources:</b> {f.get('Evidence sources')}<br/>"
                f"<b>Status:</b> {f.get('Status')}<br/>"
                f"<b>Confidence:</b> {f.get('Confidence')}",
                styles["BodyText"]
            ))
            story.append(Spacer(1, 6))
    else:
        story.append(Paragraph("No cross-document field conflicts were detected in the supported fields.", styles["BodyText"]))
    story += [Spacer(1, 8), Paragraph("4. Visual Screening", styles["Heading2"])]
    for v in case.get("visual_screening", []):
        story.append(Paragraph(str(v), styles["Small"]))
    story += [
        Spacer(1, 8), Paragraph("5. Analyst Review Notes", styles["Heading2"]),
        Paragraph((case.get("review_notes") or "No notes provided.").replace("&","&amp;"), styles["BodyText"]),
        Spacer(1, 8), Paragraph("6. Limitations and Assumptions", styles["Heading2"])
    ]
    for item in case.get("limitations", []):
        story.append(Paragraph("• " + item, styles["Small"]))
    story += [
        Spacer(1, 12),
        Paragraph(
            "<b>Important:</b> This dossier is generated by a prototype. OCR and heuristic outputs "
            "may be inaccurate. A qualified human reviewer must inspect original documents and "
            "supporting evidence before making consequential decisions.",
            styles["Small"]
        )
    ]
    doc.build(story)
    return buffer.getvalue()
